  PROCEDURE RUN_INTERNAL_WORKER(OWNER#    IN NUMBER,
                                TASK_NAME IN VARCHAR2,
                                JOB_NAME  IN VARCHAR2)
  IS
    L_START_ID           NUMBER;
    L_END_ID             NUMBER;
    L_START_ROWID        ROWID;
    L_END_ROWID          ROWID;
    L_ROWS_PROCESSED     NUMBER;
    L_CUR                INTEGER;
    L_FIRE_APPLY_TRIGGER BOOLEAN;
    L_CHUNK_ID           NUMBER;
    L_TASK               TASK_TYPE;
  BEGIN

    L_TASK := READ_TASK(OWNER#, TASK_NAME);


    IF (L_TASK.FIRE_APPLY_TRIGGER = 'TRUE') THEN L_FIRE_APPLY_TRIGGER := TRUE;
    ELSE                                         L_FIRE_APPLY_TRIGGER := FALSE;
    END IF;





    P_JOB_NAME := JOB_NAME;




    L_CUR := DBMS_SYS_SQL.OPEN_CURSOR;
    DBMS_SYS_SQL.PARSE_AS_USER(L_CUR,
                               DBMS_ASSERT.NOOP(L_TASK.SQL_STMT),
                               L_TASK.LANGUAGE_FLAG,
                               OWNER#,
                               FALSE,
                               L_TASK.EDITION,
                               L_TASK.APPLY_CROSSEDITION_TRIGGER,
                               L_FIRE_APPLY_TRIGGER);






    LOOP



        IF (IS_STOP_FLAG_SET(OWNER#, TASK_NAME)) THEN
          EXIT;
        END IF;





        IF (GET_RANGE(OWNER#, TASK_NAME, L_CHUNK_ID,
                      L_START_ROWID, L_END_ROWID, L_START_ID, L_END_ID)
            = FALSE) THEN
          EXIT;
        END IF;








        BEGIN
          IF (L_TASK.CHUNK_TYPE = ROWID_RANGE) THEN
            DBMS_SYS_SQL.BIND_VARIABLE(L_CUR, ':start_id', L_START_ROWID);
            DBMS_SYS_SQL.BIND_VARIABLE(L_CUR, ':end_id',   L_END_ROWID);
          ELSE
            DBMS_SYS_SQL.BIND_VARIABLE(L_CUR, ':start_id', L_START_ID);
            DBMS_SYS_SQL.BIND_VARIABLE(L_CUR, ':end_id',   L_END_ID);
          END IF;

          L_ROWS_PROCESSED := DBMS_SYS_SQL.EXECUTE(L_CUR);





          SET_CHUNK_STATUS(OWNER#, TASK_NAME, L_CHUNK_ID,
                           DBMS_PARALLEL_EXECUTE_BUBLIK.PROCESSED);
        EXCEPTION WHEN OTHERS THEN





          SET_CHUNK_STATUS(OWNER#, TASK_NAME, L_CHUNK_ID,
                           DBMS_PARALLEL_EXECUTE_BUBLIK.PROCESSED_WITH_ERROR,
                           SQLCODE, SQLERRM);
        END;




        COMMIT;
    END LOOP;




    DBMS_SYS_SQL.CLOSE_CURSOR(L_CUR);
  END;





  PROCEDURE STOP_TASK(OWNER#    IN NUMBER,
                      TASK_NAME IN VARCHAR2)
  IS
    L_TASK_NAME VARCHAR2(128);
    R_TASK_NAME VARCHAR2(128);
  BEGIN
    ASSERT_TASK_EXISTS(OWNER#, TASK_NAME);

    L_TASK_NAME := TASK_NAME;
    UPDATE DBMS_PARALLEL_EXECUTE_TASK$ T
      SET T.STOP_FLAG = 1
      WHERE T.TASK_OWNER# = OWNER#
        AND T.TASK_NAME   = L_TASK_NAME
      RETURNING T.TASK_NAME INTO R_TASK_NAME;

    COMMIT;
  END;


  FUNCTION OWNER_NAME_TO_NUM(OWNER_NAME IN VARCHAR2) RETURN NUMBER
  IS
    OWNER# NUMBER;
  BEGIN
    ASSERT_ARGUMENT_LENGTH(OWNER_NAME, ARG_OWNER_NAME, ARG_IDN_LEN, TRUE);

    SELECT USER_ID INTO OWNER#
      FROM DBA_USERS
      WHERE USERNAME = OWNER_NAME;

    RETURN OWNER#;
  EXCEPTION
  WHEN NO_DATA_FOUND THEN DBMS_SYS_ERROR.RAISE_SYSTEM_ERROR(-12418,OWNER_NAME);
  WHEN OTHERS        THEN RAISE;
  END;



  PROCEDURE DROP_ALL_TASKS(OWNER_NAME IN VARCHAR2)
  IS
    L_OWN NUMBER;
  BEGIN
    L_OWN := OWNER_NAME_TO_NUM(OWNER_NAME);
    DELETE FROM DBMS_PARALLEL_EXECUTE_TASK$ WHERE TASK_OWNER# = L_OWN;
  END;



  FUNCTION DEFAULT_PARALLELISM RETURN PLS_INTEGER
  IS
     NUM_SLAVES PLS_INTEGER;
  BEGIN
     WITH
     INST_CPUS AS
        (SELECT INST_ID, NVL(TO_NUMBER(VALUE), 1) CPUS
            FROM  GV$PARAMETER
            WHERE NAME = 'cpu_count'),
     INST_THREADS AS
        (SELECT INST_ID, NVL(TO_NUMBER(VALUE), 1) CPU_THREADS
            FROM  GV$PARAMETER
            WHERE NAME = 'parallel_threads_per_cpu')
     SELECT SUM((CASE WHEN CPUS <= 0 THEN 1 ELSE CPUS END) *
                (CASE WHEN CPU_THREADS <= 0 THEN 1 ELSE CPU_THREADS END))
        INTO  NUM_SLAVES
        FROM  INST_CPUS, INST_THREADS
        WHERE INST_CPUS.INST_ID = INST_THREADS.INST_ID;


     IF (NUM_SLAVES IS NULL OR NUM_SLAVES <= 0) THEN
        NUM_SLAVES := 1;
     END IF;

     RETURN NUM_SLAVES;
  END;

END;
